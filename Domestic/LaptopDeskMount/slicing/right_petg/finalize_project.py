"""Embed PrusaSlicer's effective G-code configuration into its CLI-exported 3MF."""
from pathlib import Path
import hashlib
import json
import re
import zipfile

root=Path(__file__).resolve().parent
gcode=root/'holder_right_petg.gcode'
project=root/'holder_right_petg.3mf'
ready=root/'holder_right_petg_ready.3mf'
text=gcode.read_text()
begin=text.index('; prusaslicer_config = begin')
end=text.index('; prusaslicer_config = end',begin)
settings=text[begin:end].splitlines()[1:]
config='; generated by PrusaSlicer 2.9.4; exact configuration used for holder_right_petg.gcode\n\n'+'\n'.join(settings)+'\n'
for key,value in [('support_material','1'),('perimeters','6'),('fill_density','40%'),('layer_height','0.2')]:
    assert '; '+key+' = '+value in config,(key,value)
with zipfile.ZipFile(project) as z:
    files={name:z.read(name) for name in z.namelist()}
files['Metadata/Slic3r_PE.config']=config.encode()
with zipfile.ZipFile(ready,'w',zipfile.ZIP_DEFLATED) as z:
    for name,data in files.items():z.writestr(name,data)
project.write_bytes(ready.read_bytes())
with zipfile.ZipFile(ready) as z:
    assert z.testzip() is None
    assert b'; support_material = 1' in z.read('Metadata/Slic3r_PE.config')
summary={'project':str(ready),'gcode':str(gcode),
         'gcode_sha256':hashlib.sha256(gcode.read_bytes()).hexdigest(),
         'project_configuration':'Exact effective PrusaSlicer configuration embedded, including supports.',
         'support_material':True,'perimeters':6,'infill':'40% gyroid','layer_height_mm':.2,
         'slicer_time_estimate':re.search(r'^; estimated printing time \(normal mode\) = (.+)$',text,re.M).group(1),
         'filament_length_mm':float(re.search(r'^; filament used \[mm\] = ([\d.]+)',text,re.M).group(1)),
         'filament_volume_cm3':float(re.search(r'^; filament used \[cm3\] = ([\d.]+)',text,re.M).group(1)),
         'filament_mass_g':None,'reason_mass_unknown':'The user filament preset specifies density 0.',
         'nozzle_temperature_C':230,'bed_temperature_C':[90,80]}
(root/'slice_summary.json').write_text(json.dumps(summary,ensure_ascii=False,indent=2)+'\n')
print(json.dumps(summary,ensure_ascii=False,indent=2))
